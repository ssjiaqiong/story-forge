package com.storyforge.infra.ai;

/**
 * 公共提示词块。
 *
 * <p>参考 MuMuAINovel 的 RTCO 写法：角色（Role）—任务（Task）—上下文（Context）—输出（Output），
 * 再补一组「必须 / 禁止」约束。把跨功能通用的纪律抽到这里，避免每个 Service 各写一套、
 * 质量参差。</p>
 *
 * <p>命名与标题的纪律单独成块（{@link #NAMING}、{@link #TITLES}）：模型在没有约束时，
 * 一律会落到训练语料里最高频的那几个名字和标题句式上，光说「不要俗套」没有用，
 * 必须给出可执行的取法 + 具体的禁用清单。</p>
 */
public final class PromptKit {

    private PromptKit() {
    }

    /** JSON 输出纪律：所有结构化生成共用。 */
    public static final String JSON_CONTRACT = """
            【输出纪律】
            1. 只输出一个 JSON 对象：不要解释、不要寒暄、不要 markdown 代码块、不要任何前后缀。
            2. 所有字符串值都是单行纯文本：不出现英文双引号与真实换行；需要引用时用「」。
            3. 字段没有内容就给空字符串或空数组，不要输出 null，不要编造候选名单之外的专有名词。
            """;

    /**
     * 命名纪律：角色、势力、地名、物品、称号共用。
     *
     * <p>核心是「先定文化底色，再起名」+「频次控制」+「禁用清单」三件事：
     * 模型并不知道哪些名字被写烂了，只有把烂大街的组合直接列出来，它才会绕开。</p>
     */
    public static final String NAMING = """
            【命名纪律】名字是设定的一部分，不是随手贴上去的标签。先想清楚这个人／这个地方／这件东西
            生活在什么样的文化与阶层里，再从那里取音取字；同一批产出之间要有区分度。

            1. 姓氏要杂，名要长短参差。一批里不要反复用同一个大姓，也不要把所有的名都起成两个字；
               允许复姓、地名姓、职业姓、译名姓。同族、同门可以共用辈分字，让读者一眼看出归属，
               但不同族、不同势力之间必须用字有别。

            2. 每个主要名字都要有来处，能一句话说清是谁起的、为什么叫这个：
               父母不识字就起得实在（栓住、来福、二顺），读书人起得雅（观澜、执砚、荫棠），
               门派赐名带辈分，落难改姓是为了避祸，外号来自一件具体的事而不是「人称XXX」。

            3. 读音要顺口：不用生僻字堆砌，不出现三个字同韵；同一批里的名字不要读音相近，
               免得读者分不清谁是谁。

            4. 不要用下面这些被写烂了的组合——不是这些姓不能用，而是这套「姓＋名」已经被用尽了：
               林逸、林轩、林动、叶尘、叶辰、叶凡、萧炎、萧然、苏沐雪、苏晚、苏清欢、顾清寒、
               沈墨、沈夜、秦墨、陆离、楚风、江辰、白夜、温言、谢云、慕容、南宫、独孤、上官。
               单字名也不要再用：尘、羽、寒、轩、墨、宸、煜、夜、殇、璃、若、涵、萱、瑶、婉、汐、沫。

            5. 按题材校准：
               都市／现实：要像真人名，带出生年代的痕迹；不要把 2020 年后出生的人叫成六十年代的名，
               也不要把中年人叫成偶像剧的名。
               玄幻／仙侠：可从星宿、山川、器物、诗句里取字，但别凑「常见姓＋单字文言」；
               称号要有着落（谁的封号、哪一代的排行），不要人人都叫「XX真人」「XX老祖」。
               西幻／异域：按语系统一音译规则，同一国的人名音节结构要相近，不要中西混搭。

            6. 势力名、地名、物品名同样适用：名字要透露功能、来历或立场（修缮行会、抬尸巷、放血契），
               不要「天机阁」「万宝楼」「神秘组织」这种换个题材也能用的空壳。
            """;

    /**
     * 标题纪律：总纲标题、章节标题、卷名、事件标题共用。
     *
     * <p>好的标题是「读者读完之后回头一看，发现标题说的正是这一章最要命的那个东西」，
     * 所以要求取具体物件、动作、台词、数字，而不是概括情绪。</p>
     */
    public static final String TITLES = """
            【标题纪律】标题是读者用来索引这一段的抓手，不是作者写给自己看的摘要。

            1. 每一条都要落在一个具体的东西上：一件物品、一个动作、一句台词、一个地点、一个数字、
               一个时辰。读者只看标题，就能大致猜到这一段里出了什么事。

            2. 禁用空泛词：危机、转机、真相、决战、抉择、觉醒、逆袭、阴谋、暗流、风暴、命运、
               惊变、之夜、之谜、之战、序曲、终章。

            3. 禁用三种已经被写烂的句式：
               - 四字成语式（暗流涌动、风起云涌、初露锋芒、峰回路转）
               - 「XX的XX」对称式（暴风雨前的宁静、黎明前的黑暗、最后的晚餐）
               - 并列对举（血与火、光与影、生与死、罪与罚）

            4. 同一批里句式和字数都要错开：一条取物、一条取动作、一条取一句台词；
               长度在要求范围内浮动，不要条条卡在同一个字数，也不要条条都是名词短语。

            5. 不要与已有标题撞结构：先看已有标题是怎么起的，换一种取法。
            """;

    /**
     * 反机械化：结构化生成（总纲、大纲、角色、事件）共用。
     *
     * <p>模型的默认行为是「每条都按同一个模板平推」，读起来就有一股流水线味道。
     * 这里要求它主动打破对称：节奏不统一、人不必人人都有秘密、数量词不要重复。</p>
     */
    public static final String ANTI_MECHANICAL = """
            【反机械化】同一种结构连着写几条，机器味就出来了。
            1. 推进节奏不要统一：有的直接砸事件，有的从一个细节切进去，有的用一段对话开场；
               不要每条都按「开局—矛盾—转折—结果」四段平推。
            2. 不要给每个人都配齐「秘密＋致命缺陷＋成长弧」：一半人靠习惯、立场、处境立住就够了，
               写满反而假。
            3. 同一段里不要连用「不是……而是……」「不仅……更是……」「既……又……」这类对举句式，
               最多出现一次。
            4. 数量词和程度词要具体且不重复：不要满篇「三个」「数倍」「短短几天」。
            5. 删掉解释性过渡（与此同时、就在这时、就这样、不知不觉间），直接切到场景。
            """;

    /** 设定类内容的去陈词要求。 */
    public static final String ANTI_CLICHE = """
            【去陈词】
            - 禁止「天赋异禀」「深不可测」「倾国倾城」「神秘莫测」「价值连城」「不凡」「绝美」这类标签。
            - 禁止用抽象形容词代替具体设定：能力要写清边界与代价，人物要写清欲望与缺陷。
            - 禁止「命运的齿轮开始转动」「暴风雨前的宁静」「这一切才刚刚开始」「真正的考验还在后面」这类句式。
            - 禁止用「所有人都震惊了」「无人敢相信」代替具体反应：写谁做了什么、说了什么。
            """;

    /** 正文写作的去 AI 味要求。 */
    public static final String PROSE_RULES = """
            【文风与反 AI 味】
            - 禁用总结腔：「总之」「综上所述」「值得注意的是」「不难看出」「这一切都」「命运的齿轮」。
            - 禁用模板化描写：「空气仿佛凝固」「嘴角勾起一抹弧度」「深邃的眼眸」「心中一凛」「瞳孔骤缩」
              「深吸一口气」「缓缓」「微微」「淡淡」——这些词不是绝对不能用，但整章加起来不超过三处。
            - 慎用副词与转折词：突然、渐渐、瞬间、不禁、竟然、缓缓。删掉之后句子还成立，就删掉。
            - 抽象情绪要落到身体反应、动作、物件或对话上，不要直接贴标签（紧张、愤怒、悲伤）。
            - 对话要像人说话：允许打断、答非所问、说半句、沉默；不要在对话里交代设定，
              不要让每个人都把话说完整、说清楚。
            - 长短句交替：动作场景用短句，压迫感或回忆场景可以放长句；段落长度也要参差，不要一段一块砖。
            """;

    /** 按题材校准设定尺度，避免所有题材都写成宏大架空。 */
    public static final String GENRE_GUIDE = """
            【类型校准】
            - 玄幻/仙侠：写清力量从哪来、代价是什么、境界差如何体现在日常与战斗里；宗门与王朝的资源、规矩要能运转。
            - 都市：落到具体行业、城市肌理、职场与阶层规则；少写架空财阀，多写真实流程与人情。
            - 悬疑/推理：先定信息差与嫌疑链，再写事件；每条线索都要能指向或排除具体的人。
            - 科幻：先定技术边界与社会后果，再写奇观；技术不能只在需要时万能。
            - 历史：尊重制度、礼法、财政与交通约束；人物不能拥有时代没有的常识。
            - 未指定类型：按核心创意判断，不要默认大崩解、末日、系统面板。
            """;
}
